use backend_lib::models::*;
use specta::Types;
use specta_zod::{BigIntExportBehavior, Zod};

fn main() {
    let mut builder = Types::default();
    builder.register_mut::<IpcPayloadData>();
    builder.register_mut::<FolderReportStatus>();
    builder.register_mut::<FailedFile>();
    builder.register_mut::<SubtitleMetadata>();
    builder.register_mut::<DirectoryStats>();
    builder.register_mut::<FileStat>();

    let mut zod_str = Zod::default()
        .bigint(BigIntExportBehavior::Number)
        .export(&builder, &specta_serde::Format)
        .unwrap();

    // Workaround for specta-zod 0.0.3 alphabetically sorting types,
    // which might cause ReferenceError if DirectoryStats comes before FileStat.
    zod_str = zod_str.replace(
        "z.array(FileStatSchema)",
        "z.array(z.lazy(() => FileStatSchema))",
    );
    zod_str = zod_str.replace(
        "z.array(FailedFileSchema)",
        "z.array(z.lazy(() => FailedFileSchema))",
    );
    zod_str = zod_str.replace(
        "z.array(SubtitleMetadataSchema)",
        "z.array(z.lazy(() => SubtitleMetadataSchema))",
    );

    let manifest_dir = env!("CARGO_MANIFEST_DIR");
    let out_path = std::path::PathBuf::from(manifest_dir).join("../frontend/src/lib/types/ipc.ts");

    // Create the directory if it doesn't exist
    if let Some(parent) = out_path.parent() {
        std::fs::create_dir_all(parent).unwrap();
    }

    // Include the warning header
    let final_content = format!(
        "// This file was generated by [specta]. DO NOT EDIT.\n// Run `pnpm run generate:types` to update it.\n\n{}",
        zod_str
    );

    std::fs::write(out_path, final_content).unwrap();
    println!("Successfully exported Zod schemas to frontend/src/lib/types/ipc.ts");
}
